#!/bin/sh
# End-to-end test in a throwaway network namespace (no root needed).
# usage: tests/netns.sh path/to/routebot
set -eu

if [ -z "${RB_IN_NS:-}" ]; then
	exec unshare -rn env RB_IN_NS=1 sh "$0" "$@"
fi

RB=$(realpath "$1")
T=$(mktemp -d)
LOG=$T/log
: > "$LOG"
PID=
FAILS=0

cleanup() {
	[ -n "$PID" ] && kill "$PID" 2>/dev/null || true
	rm -rf "$T"
}
trap cleanup EXIT

pass() { echo "ok   $*"; }
fail() { echo "FAIL $*"; FAILS=$((FAILS + 1)); }

# normalized command output: no trailing spaces
out() { "$@" 2>&1 | sed 's/[[:space:]]*$//'; }

has() {
	_line=$1; shift
	if out "$@" | grep -qxF -- "$_line"; then pass "'$*' has '$_line'"
	else fail "'$*' lacks '$_line'"; out "$@" | sed 's/^/     | /'; fi
}

hasnt() {
	_line=$1; shift
	if out "$@" | grep -qxF -- "$_line"; then fail "'$*' still has '$_line'"
	else pass "'$*' lacks '$_line'"; fi
}

empty() {
	if [ -z "$(out "$@")" ]; then pass "'$*' is empty"
	else fail "'$*' not empty"; out "$@" | sed 's/^/     | /'; fi
}

mark() { MARK=$(wc -l < "$LOG"); }

wait_log() {
	for _ in $(seq 50); do
		tail -n +"$((MARK + 1))" "$LOG" | grep -qF -- "$1" && { pass "log: $1"; return 0; }
		sleep 0.1
	done
	fail "log never said: $1"
	tail -n 20 "$LOG" | sed 's/^/     | /'
	return 0
}

start() {
	mark
	"$RB" -v -c "$T/config" >> "$LOG" 2>&1 &
	PID=$!
	wait_log "running"
}

stop() {
	kill -TERM "$PID"
	wait "$PID" && pass "exit status 0" || fail "exit status $?"
	PID=
}

hup() { mark; kill -HUP "$PID"; }

# --- topology ---
ip link set lo up
ip link add vpn0 type dummy
ip link set vpn0 arp off up			# NOARP: usable without a gateway
ip link add wan0 type veth peer name wanp
ip addr add 192.0.2.2/24 dev wan0
ip -6 addr add 2001:db8::2/64 dev wan0 nodad
ip link set wanp up
ip link set wan0 up
ip route add default via 192.0.2.1 dev wan0
ip -6 route add default via 2001:db8::1 dev wan0

mkdir -p "$T/lists" "$T/misc"
cat > "$T/lists/a.lst" <<EOF
# generated by test
1.0.0.0/24
1.1.1.0/24	# trailing comment

10.0.0.1/8
not-a-cidr
2606:4700::/32
EOF
printf '1.1.1.0/24\n8.8.8.0/24\n' > "$T/lists/b.lst"
printf '9.9.9.0/24\n1.0.0.0/24\n' > "$T/misc/x.lst"

write_config() {
	cat > "$T/config" <<EOF
config routebot
	option fwmask '0xff000000'
	option table_id '${TABLE_ID:-10000}'
	option iface_prio '10000'
	option rule_prio '20000'

EOF
	for i in $IFACES; do
		case $i in
		vpn0) printf "config interface 'vpn0'\n\toption fwmark '0x12'\n\n" ;;
		wan0) printf "config interface 'wan0'\n\toption fwmark '0xaa'\n\n" ;;
		esac >> "$T/config"
	done
	cat >> "$T/config" <<EOF
config rule 'warp'
	option iface 'vpn0'
	list cidrset '$T/lists/*.lst'

config rule 'misc'
	option iface 'wan0'
	list cidrset '$T/misc/*'
	list cidrset '$T/nothing/*'
EOF
}

IFACES="vpn0 wan0"
write_config

echo "== startup"
start
has "1.0.0.0/24 dev vpn0 proto 233 scope link" ip route show table 10000
has "1.1.1.0/24 dev vpn0 proto 233 scope link" ip route show table 10000
has "10.0.0.0/8 dev vpn0 proto 233 scope link" ip route show table 10000
has "8.8.8.0/24 dev vpn0 proto 233 scope link" ip route show table 10000
has "9.9.9.0/24 via 192.0.2.1 dev wan0 proto 233" ip route show table 10000
has "2606:4700::/32 dev vpn0 proto 233 metric 1024 pref medium" ip -6 route show table 10000
has "default dev vpn0 proto 233 scope link" ip route show table 10001
has "default via 192.0.2.1 dev wan0 proto 233" ip route show table 10002
has "default via 2001:db8::1 dev wan0 proto 233 metric 1024 pref medium" ip -6 route show table 10002
has "10001:	from all fwmark 0x12000000/0xff000000 lookup 10001 proto 233" ip rule
has "10002:	from all fwmark 0xaa000000/0xff000000 lookup 10002 proto 233" ip rule
has "20000:	from all fwmark 0/0xff000000 lookup 10000 proto 233" ip rule
has "20000:	from all fwmark 0/0xff000000 lookup 10000 proto 233" ip -6 rule
grep -q "claimed by rule 'warp' (vpn0) and rule 'misc' (wan0)" "$LOG" && pass "conflict warned" || fail "no conflict warning"
grep -q "invalid CIDR 'not-a-cidr'" "$LOG" && pass "bad line warned" || fail "no bad line warning"

echo "== iface down -> blackhole"
mark; ip link set vpn0 down; wait_log "sync (link event)"
has "blackhole 1.0.0.0/24 proto 233" ip route show table 10000
has "blackhole 2606:4700::/32 dev lo proto 233 metric 1024 pref medium" ip -6 route show table 10000
has "blackhole default proto 233" ip route show table 10001
has "9.9.9.0/24 via 192.0.2.1 dev wan0 proto 233" ip route show table 10000

echo "== iface up -> restored"
mark; ip link set vpn0 up; wait_log "sync (link event)"
has "1.0.0.0/24 dev vpn0 proto 233 scope link" ip route show table 10000
has "default dev vpn0 proto 233 scope link" ip route show table 10001

echo "== gateway change"
mark; ip route replace default via 192.0.2.3 dev wan0; wait_log "sync (link event)"
has "9.9.9.0/24 via 192.0.2.3 dev wan0 proto 233" ip route show table 10000
has "default via 192.0.2.3 dev wan0 proto 233" ip route show table 10002

echo "== gateway gone on L2 iface -> blackhole v4 only"
mark; ip route del default dev wan0; wait_log "sync (link event)"
has "blackhole 9.9.9.0/24 proto 233" ip route show table 10000
has "blackhole default proto 233" ip route show table 10002
has "default via 2001:db8::1 dev wan0 proto 233 metric 1024 pref medium" ip -6 route show table 10002
mark; ip route add default via 192.0.2.1 dev wan0; wait_log "sync (link event)"
has "9.9.9.0/24 via 192.0.2.1 dev wan0 proto 233" ip route show table 10000

echo "== reload: list diff"
printf '1.1.1.0/24\n4.4.4.0/24\n' > "$T/lists/b.lst"
hup; wait_log "1 routes set, 1 deleted, 0 rules added, 0 deleted"
has "4.4.4.0/24 dev vpn0 proto 233 scope link" ip route show table 10000
hasnt "8.8.8.0/24 dev vpn0 proto 233 scope link" ip route show table 10000

echo "== reload: no-op"
hup; wait_log "sync (reload): nothing to do"

echo "== reload: broken config keeps old state"
cp "$T/config" "$T/config.good"
printf "config rule 'bad'\n\toption iface 'nope'\n" >> "$T/config"
hup; wait_log "reload failed, keeping the old config"
has "4.4.4.0/24 dev vpn0 proto 233 scope link" ip route show table 10000
mv "$T/config.good" "$T/config"

echo "== reload: swap interface order"
IFACES="wan0 vpn0"; write_config
hup; wait_log "sync (reload)"
has "default dev vpn0 proto 233 scope link" ip route show table 10002
has "default via 192.0.2.1 dev wan0 proto 233" ip route show table 10001
has "10001:	from all fwmark 0xaa000000/0xff000000 lookup 10001 proto 233" ip rule
has "10002:	from all fwmark 0x12000000/0xff000000 lookup 10002 proto 233" ip rule
hasnt "10001:	from all fwmark 0x12000000/0xff000000 lookup 10001 proto 233" ip rule
# 1.0.0.0/24 now: first rule in config order still 'warp' -> vpn0
has "1.0.0.0/24 dev vpn0 proto 233 scope link" ip route show table 10000

echo "== link deleted and recreated (new ifindex)"
mark; ip link del vpn0; wait_log "sync (link event)"
has "blackhole 1.0.0.0/24 proto 233" ip route show table 10000
mark; ip link add vpn0 type dummy; ip link set vpn0 arp off up; wait_log "sync (link event)"
has "1.0.0.0/24 dev vpn0 proto 233 scope link" ip route show table 10000

echo "== reload: global params change"
TABLE_ID=30000; write_config
hup; wait_log "sync (reload)"
empty ip route show table 10000
has "1.0.0.0/24 dev vpn0 proto 233 scope link" ip route show table 30000
has "20000:	from all fwmark 0/0xff000000 lookup 30000 proto 233" ip rule
hasnt "20000:	from all fwmark 0/0xff000000 lookup 10000 proto 233" ip rule

echo "== SIGTERM cleans up"
stop
empty ip route show table all proto 233
empty ip -6 route show table all proto 233
if ip rule | grep -q "proto 233"; then fail "rules left"; else pass "no rules left"; fi

echo "== crash leftovers are flushed on start"
start
kill -KILL "$PID"; wait "$PID" 2>/dev/null || true; PID=
has "20000:	from all fwmark 0/0xff000000 lookup 30000 proto 233" ip rule
TABLE_ID=10000; write_config
start
grep -q "flush: removed" "$LOG" && pass "stale state flushed" || fail "no flush"
empty ip route show table 30000
has "1.0.0.0/24 dev vpn0 proto 233 scope link" ip route show table 10000
if [ "$(ip rule | grep -c 'proto 233')" = 3 ]; then pass "3 v4 rules"; else fail "rule count"; ip rule; fi
stop

if grep -q "ERROR: AddressSanitizer\|runtime error:" "$LOG"; then
	fail "sanitizer reports"; grep -A5 "Sanitizer\|runtime error" "$LOG"
fi

echo
[ -n "${SHOW_LOG:-}" ] && { echo "--- log"; cat "$LOG"; }
[ "$FAILS" = 0 ] && echo "all passed" || { echo "$FAILS failed"; echo "--- log"; cat "$LOG"; exit 1; }
