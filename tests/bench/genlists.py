#!/usr/bin/env python3
"""Generate the benchmark's CIDR list files, deterministically.

usage: genlists.py OUTDIR

Writes, under OUTDIR:
  big/big-{1,2,3}.lst  rule 'big' (group pool): ~150k v4 + ~20k v6
  asn/as13335.lst      rule 'asn' (group warp): 3k v4 + 1.5k v6, 5% also in big
  misc/m00..m09.lst    rule 'misc' (group wan): 10 x 500 entries
  alt/m03.lst          m03.lst with 100 entries removed and 100 others added
  manifest.json        what routebot should end up with, and a content hash

The lists carry the noise real ones do: ~3% exact duplicates in big, ~1%
lines with host bits set, ~0.1% invalid lines, comment lines, trailing
comments, blank lines, stray whitespace and the odd CRLF.

Same seed, same bytes: everything comes from one random.Random(SEED) and only
getrandbits() is used, whose output is stable across Python versions.
"""
import hashlib
import ipaddress
import json
import os
import sys

import random

SEED = 20261016

N_BIG_V4 = 150_000
N_BIG_V6 = 20_000
N_ASN_V4 = 3_000
N_ASN_V6 = 1_500
ASN_SHARED = 0.05	# fraction of asn entries copied from big
N_MISC_FILES = 10
N_MISC_PER_FILE = 500
MISC_V6 = 0.10
N_ALT = 100		# entries swapped in alt/m03.lst
ALT_FILE = 3

# documentation, private, loopback, link-local, multicast, the bench topology...
RESERVED_V4 = [ipaddress.ip_network(n) for n in (
	"0.0.0.0/8", "10.0.0.0/8", "100.64.0.0/10", "127.0.0.0/8", "169.254.0.0/16",
	"172.16.0.0/12", "192.0.0.0/24", "192.0.2.0/24", "192.168.0.0/16",
	"198.18.0.0/15", "198.51.100.0/24", "203.0.113.0/24", "224.0.0.0/3")]
RESERVED_V6 = [ipaddress.ip_network(n) for n in ("2001::/23", "2001:db8::/32", "2002::/16")]
V6_RIR_BLOCKS = [0x2001, 0x2400, 0x2600, 0x2800, 0x2a00, 0x2c00]

rng = random.Random(SEED)


def rand_below(n):
	"""Uniform in [0, n), from getrandbits only."""
	k = max(1, n.bit_length())
	while True:
		v = rng.getrandbits(k)
		if v < n:
			return v


def chance(p):
	return rand_below(1_000_000) < p * 1_000_000


def pick_weighted(table):
	"""table: [(weight, value)], integer weights."""
	r = rand_below(sum(w for w, _ in table))
	for w, v in table:
		if r < w:
			return v
		r -= w
	raise AssertionError


V4_PLEN = [(720, 24), (230, None), (20, "small"), (30, 32)]	# None: /12../23
V6_PLEN = [(150, 32), (250, None), (400, 48), (80, 56), (70, 64), (50, 128)]	# None: /33../47


def v4_plen():
	p = pick_weighted(V4_PLEN)
	if p is None:
		# shorter ones are rarer: weight /12../23 by 1..12
		return pick_weighted([(i + 1, 12 + i) for i in range(12)])
	if p == "small":
		return 25 + rand_below(7)
	return p


def v6_plen():
	p = pick_weighted(V6_PLEN)
	return 33 + rand_below(15) if p is None else p


def v4_net():
	plen = v4_plen()
	addr = rng.getrandbits(32)
	return ipaddress.ip_network((addr, plen), strict=False), addr


def v6_net():
	plen = v6_plen()
	top = V6_RIR_BLOCKS[rand_below(len(V6_RIR_BLOCKS))]
	if top != 0x2001:
		top += rand_below(16)
	addr = (top << 112) | rng.getrandbits(112)
	return ipaddress.ip_network((addr, plen), strict=False), addr


used = set()


def fresh(gen, reserved):
	"""A prefix nobody else has, clear of reserved space; plus a random host address in it."""
	while True:
		net, addr = gen()
		if net in used or any(net.overlaps(r) for r in reserved):
			continue
		used.add(net)
		return net, addr


def fresh_v4():
	return fresh(v4_net, RESERVED_V4)


def fresh_v6():
	return fresh(v6_net, RESERVED_V6)


def sort_key(net):
	return (net.version, int(net.network_address), net.prefixlen)


INVALID = ["300.1.2.0/24", "1.2.3.0/33", "1.2.3/24", "2001:zz::/32", "2a00::/129",
	   "example.com", "1.2.3.4/", "/24", "1.2.3.4/abc", "fe80::1%eth0/64", "1.2.3.4 - 1.2.3.9"]


class Lines:
	"""Render entries into list file lines with noise; counts what it adds."""

	def __init__(self, stats):
		self.st = stats

	def entry(self, net, addr, hostbits_p):
		if hostbits_p and net.prefixlen < net.max_prefixlen and chance(hostbits_p):
			host = addr & ((1 << (net.max_prefixlen - net.prefixlen)) - 1)
			if host:
				self.st["hostbits_lines"] += 1
				ip = ipaddress.ip_address(int(net.network_address) | host)
				return f"{ip}/{net.prefixlen}"
		return str(net)

	def decorate(self, text, ac=None):
		if chance(0.02):
			text += ("  # " if chance(0.5) else "\t# ") + (ac or f"AS{rand_below(400000)}")
		if chance(0.005):
			text = " " * (1 + rand_below(3)) + text
		if chance(0.005):
			text += "\t" if chance(0.5) else "   "
		if chance(0.001):
			text += "\r"
		return text

	def render(self, items, title, hostbits_p=0.01, invalid_p=0.001, dupes=()):
		"""items: [(net, addr)] in output order; dupes: [(pos, net, addr)]."""
		out = [f"# {title}", f"# generated by tests/bench/genlists.py (seed {SEED})", ""]
		dupes = sorted(dupes, key=lambda d: d[0])
		di = 0
		for i, (net, addr) in enumerate(items):
			while di < len(dupes) and dupes[di][0] <= i:
				_, dn, da = dupes[di]
				out.append(self.decorate(self.entry(dn, da, 0)))
				di += 1
			out.append(self.decorate(self.entry(net, addr, hostbits_p)))
			if chance(invalid_p):
				self.st["invalid_lines"] += 1
				out.append(INVALID[rand_below(len(INVALID))])
			if chance(0.004):
				out.append("")
			if chance(0.003):
				out.append(f"# --- block {i} ---")
		while di < len(dupes):
			out.append(self.entry(dupes[di][1], dupes[di][2], 0))
			di += 1
		return "\n".join(out) + "\n"


def write(path, text):
	os.makedirs(os.path.dirname(path), exist_ok=True)
	with open(path, "w", newline="") as f:
		f.write(text)


def main():
	if len(sys.argv) != 2:
		sys.exit("usage: genlists.py OUTDIR")
	outdir = sys.argv[1]
	st = {"hostbits_lines": 0, "invalid_lines": 0, "dupe_lines": 0}
	lines = Lines(st)
	files = {}

	# --- big: 2 files of v4, 1 of v4 tail + v6, each sorted like a dump
	big4 = [fresh_v4() for _ in range(N_BIG_V4)]
	big6 = [fresh_v6() for _ in range(N_BIG_V6)]
	third = N_BIG_V4 // 3
	parts = [big4[:third], big4[third:2 * third], big4[2 * third:] + big6]
	for k, part in enumerate(parts):
		part.sort(key=lambda e: sort_key(e[0]))
		# ~3% exact duplicates, of entries anywhere in big, at random spots
		dupes = []
		for _ in range(len(part) * 3 // 100):
			src = parts[rand_below(3)]
			net, addr = src[rand_below(len(src))]
			dupes.append((rand_below(len(part)), net, addr))
		st["dupe_lines"] += len(dupes)
		files[f"big/big-{k + 1}.lst"] = lines.render(part, f"big list part {k + 1}", dupes=dupes)

	# --- asn: mostly its own, 5% shared with big (big comes first: big wins)
	n_sh4, n_sh6 = int(N_ASN_V4 * ASN_SHARED), int(N_ASN_V6 * ASN_SHARED)
	asn = [fresh_v4() for _ in range(N_ASN_V4 - n_sh4)] + [fresh_v6() for _ in range(N_ASN_V6 - n_sh6)]
	shared = set()
	while len(shared) < n_sh4:
		shared.add(rand_below(N_BIG_V4))
	asn += [big4[i] for i in sorted(shared)]
	shared6 = set()
	while len(shared6) < n_sh6:
		shared6.add(rand_below(N_BIG_V6))
	asn += [big6[i] for i in sorted(shared6)]
	asn.sort(key=lambda e: sort_key(e[0]))
	files["asn/as13335.lst"] = lines.render(asn, "AS13335 announced prefixes", hostbits_p=0)

	# --- misc: small hand-maintained-looking files, mostly v4
	misc = []
	for k in range(N_MISC_FILES):
		ents = [fresh_v6() if chance(MISC_V6) else fresh_v4() for _ in range(N_MISC_PER_FILE)]
		misc.append(ents)
		files[f"misc/m{k:02d}.lst"] = lines.render(ents, f"misc list {k}", hostbits_p=0.01)

	# --- alt/m03.lst: 100 out, 100 in; rendered without random noise so the
	# swap is exactly 100 routes each way
	base = misc[ALT_FILE]
	drop = set()
	while len(drop) < N_ALT:
		drop.add(rand_below(len(base)))
	alt = [e for i, e in enumerate(base) if i not in drop] + [fresh_v4() for _ in range(N_ALT)]
	files[f"alt/m{ALT_FILE:02d}.lst"] = "".join(f"{n}\n" for n, _ in alt)
	files[f"misc/m{ALT_FILE:02d}.lst"] = "".join(f"{n}\n" for n, _ in base)

	h = hashlib.sha256()
	for name in sorted(files):
		write(os.path.join(outdir, name), files[name])
		h.update(name.encode() + b"\0" + files[name].encode() + b"\0")

	big_set = {n for n, _ in big4 + big6}
	asn_own = [n for n, _ in asn if n not in big_set]
	misc_all = [n for ents in misc for n, _ in ents]
	v4 = lambda ns: sum(1 for n in ns if n.version == 4)
	manifest = {
		"seed": SEED,
		"sha256": h.hexdigest(),
		"lines": sum(t.count("\n") for t in files.values()),
		"routes": {
			"big": {"v4": N_BIG_V4, "v6": N_BIG_V6},
			"asn": {"v4": v4(asn_own), "v6": len(asn_own) - v4(asn_own)},
			"misc": {"v4": v4(misc_all), "v6": len(misc_all) - v4(misc_all)},
		},
		"conflicts": n_sh4 + n_sh6,
		"alt_file": f"m{ALT_FILE:02d}.lst",
		"alt_swapped": N_ALT,
		**st,
	}
	r = manifest["routes"]
	manifest["routes"]["total"] = {f: sum(r[k][f] for k in ("big", "asn", "misc")) for f in ("v4", "v6")}
	write(os.path.join(outdir, "manifest.json"), json.dumps(manifest, indent=1) + "\n")
	print(json.dumps({"sha256": manifest["sha256"], "routes": manifest["routes"]["total"]}))


if __name__ == "__main__":
	main()
